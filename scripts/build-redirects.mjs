#!/usr/bin/env node
/**
 * Generates the CloudFront viewer-request function from docs/url-inventory.csv
 * and src/data/wp-shortlinks.json, then writes it to:
 *   infra/cloudfront-function.js                 (reviewable copy)
 *   infra/cloudformation-website-hosting.yml     (between the GENERATED markers)
 *
 *   npm run redirects
 *
 * Why a function: Astro's `redirects` emit meta-refresh HTML on static hosting;
 * search engines need real 301s and 410s, so they are answered at the edge.
 * CloudFront Functions are limited to 10 KB, so rules are compacted:
 * thin tag archives are "everything except the kept tags → /blog/" instead of a list.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const CSV = path.join(ROOT, 'docs/url-inventory.csv');
const SHORTLINKS = path.join(ROOT, 'src/data/wp-shortlinks.json');
const OUT_JS = path.join(ROOT, 'infra/cloudfront-function.js');
const TEMPLATE = path.join(ROOT, 'infra/cloudformation-website-hosting.yml');
const MAX_BYTES = 10 * 1024;

function parseCsv(text) {
  const [header, ...lines] = text.trim().split('\n');
  const cols = header.split(',');
  return lines.map((line) => {
    const cells = [];
    let cur = '';
    let quoted = false;
    for (const ch of line) {
      if (ch === '"') quoted = !quoted;
      else if (ch === ',' && !quoted) {
        cells.push(cur);
        cur = '';
      } else cur += ch;
    }
    cells.push(cur);
    return Object.fromEntries(cols.map((c, i) => [c, cells[i] ?? '']));
  });
}

const rows = parseCsv(readFileSync(CSV, 'utf8'));
const isPattern = (p) => p.includes('*') || p.includes('?') || p.includes(',');

const keptTags = rows.filter((r) => r.type === 'tag' && r.action === 'keep').map((r) => r.old_path.split('/')[2]);
const exact = {};
const gone = [];
for (const r of rows) {
  if (isPattern(r.old_path) || r.type === 'tag') continue;
  if (r.action === '301') exact[r.old_path] = r.target;
  if (r.action === '410' && !r.old_path.startsWith('/?')) gone.push(r.old_path);
}
// Gone sections are matched by prefix, so collapse e.g. 16 /portfolio/<x>/ rows into one rule.
const goneSet = new Set(gone);
const gonePrefixes = ['/portfolio/', '/portfolio-category/', '/elementskit-content/', '/wp-admin', '/wp-login.php', '/xmlrpc.php', '/wp-json/', '/comments/feed/'];
const goneExact = [...goneSet].filter((p) => !gonePrefixes.some((pre) => p.startsWith(pre)));

const shortlinks = JSON.parse(readFileSync(SHORTLINKS, 'utf8'));
// "p=123": "/slug/" → { "123": "/slug/" } (page ids share the namespace with post ids in WordPress)
const ids = {};
for (const [key, target] of Object.entries(shortlinks)) ids[key.split('=')[1]] = target;

const code = `// GENERATED by scripts/build-redirects.mjs from docs/url-inventory.csv — do not edit by hand.
var R = ${JSON.stringify(exact)};
var KEEP_TAGS = ${JSON.stringify(Object.fromEntries(keptTags.map((t) => [t, 1])))};
var GONE = ${JSON.stringify(gonePrefixes)};
var GONE_EXACT = ${JSON.stringify(Object.fromEntries(goneExact.map((p) => [p, 1])))};
var IDS = ${JSON.stringify(ids)};

function qs(request) {
  var parts = [];
  var params = request.querystring;
  for (var key in params) {
    var entry = params[key];
    var values = entry.multiValue ? entry.multiValue : [entry];
    for (var i = 0; i < values.length; i++) parts.push(values[i].value === '' ? key : key + '=' + values[i].value);
  }
  return parts.length ? '?' + parts.join('&') : '';
}

function moved(location) {
  return { statusCode: 301, statusDescription: 'Moved Permanently', headers: { location: { value: location }, 'cache-control': { value: 'public, max-age=86400' } } };
}

function gone() {
  return { statusCode: 410, statusDescription: 'Gone', headers: { 'cache-control': { value: 'public, max-age=86400' } } };
}

// www.<domain>: answer with ONE 301 straight to the final apex URL (no redirect chains),
// by running the apex rules first and turning their result into an absolute redirect.
function handler(event) {
  var request = event.request;
  var host = request.headers.host ? request.headers.host.value : '';
  if (host.indexOf('www.') !== 0) return route(request);
  var apex = 'https://' + host.substring(4);
  var original = request.uri;
  var out = route(request);
  if (out.statusCode === 301) {
    var loc = out.headers.location.value;
    return moved(loc.charAt(0) === '/' ? apex + loc : loc);
  }
  if (out.statusCode) return out; // 410 Gone stays 410
  return moved(apex + original + qs(request));
}

function route(request) {
  var uri = request.uri;
  var q = request.querystring;

  // WordPress shortlinks and query-string pages on the home page.
  if (uri === '/') {
    var id = (q.p && q.p.value) || (q.page_id && q.page_id.value);
    if (id) return moved(IDS[id] || '/');
    if (q.elementskit_template) return gone();
  }

  var path = uri.charAt(uri.length - 1) === '/' ? uri : uri + '/';
  for (var g = 0; g < GONE.length; g++) if (uri.indexOf(GONE[g]) === 0) return gone();
  if (GONE_EXACT[path]) return gone();
  if (R[path] || R[uri]) return moved(R[path] || R[uri]); // pages and files (/sitemap.xml)
  if (/\\/feed\\/$/.test(path)) return moved('/rss.xml');
  if (path.indexOf('/author/') === 0) return moved('/blog/');
  var tag = path.match(/^\\/tag\\/([^/]+)\\//);
  if (tag && !KEEP_TAGS[tag[1]]) return moved('/blog/');

  var last = uri.substring(uri.lastIndexOf('/') + 1);
  if (last.indexOf('.') !== -1) return request; // a file: /rss.xml, /_astro/x.css, /pagefind/...
  if (uri.charAt(uri.length - 1) !== '/') return moved(uri + '/' + qs(request));
  request.uri = uri + 'index.html';
  return request;
}
`;

const bytes = Buffer.byteLength(code);
if (bytes > MAX_BYTES) {
  console.error(`CloudFront function is ${bytes} bytes (> ${MAX_BYTES}). Compact the rules or move them to a KeyValueStore.`);
  process.exit(1);
}
writeFileSync(OUT_JS, code);

const template = readFileSync(TEMPLATE, 'utf8');
const BEGIN = '        // BEGIN GENERATED FUNCTION';
const END = '        // END GENERATED FUNCTION';
const start = template.indexOf(BEGIN);
const end = template.indexOf(END);
if (start === -1 || end === -1) throw new Error('GENERATED markers not found in the CloudFormation template');
const indented = code
  .trimEnd()
  .split('\n')
  .map((l) => (l ? '        ' + l : ''))
  .join('\n');
writeFileSync(TEMPLATE, template.slice(0, start) + BEGIN + '\n' + indented + '\n' + template.slice(end));

console.log(
  `CloudFront function: ${bytes} bytes · ${Object.keys(exact).length} exact 301s · ${keptTags.length} kept tags · ` +
    `${Object.keys(ids).length} shortlinks · ${gonePrefixes.length + goneExact.length} gone rules`,
);
